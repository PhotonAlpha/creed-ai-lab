-- Saved analyses per release and the human review of each item.
-- Written to run unchanged on PostgreSQL and on H2 (MODE=PostgreSQL), so the tests execute these exact
-- migrations: identity columns, no `comment on`, no PostgreSQL-only types.

create table mr_release (
    id          bigint generated by default as identity primary key,
    name        varchar(120)             not null,
    description varchar(1000),
    created_at  timestamp with time zone not null,
    constraint ux_mr_release_name unique (name)
);

-- One run of the comparison. result_json holds everything but the items (source, refactorings, changed
-- files, warnings) so a saved analysis renders exactly like a live one.
create table mr_analysis (
    id            bigint generated by default as identity primary key,
    release_id    bigint                   not null references mr_release (id),
    mode          varchar(16)              not null,
    repo1_path    varchar(1000)            not null,
    repo2_path    varchar(1000)            not null,
    baseline_ref  varchar(1000)            not null,
    total_items   integer                  not null,
    high_items    integer                  not null,
    medium_items  integer                  not null,
    low_items     integer                  not null,
    duration_ms   bigint                   not null,
    analyzed_at   timestamp with time zone not null,
    result_json   text                     not null
);
create index ix_mr_analysis_release on mr_analysis (release_id, analyzed_at);

-- One risk item and its review. item_key is RiskItem.id (stable across runs); fingerprint hashes the content
-- that a reviewer judged, minus line numbers, so a re-run can carry an unchanged item's review forward.
create table mr_item (
    id                bigint generated by default as identity primary key,
    analysis_id       bigint        not null references mr_analysis (id) on delete cascade,
    item_key          varchar(1000) not null,
    fingerprint       varchar(64)   not null,
    level             varchar(10)   not null,
    category          varchar(32)   not null,
    element           varchar(1000) not null,
    item_json         text          not null,
    review_status     varchar(16)   not null,
    review_note       varchar(2000),
    reviewed_by       varchar(120),
    reviewed_at       timestamp with time zone,
    carried_over_from bigint,
    version           bigint        not null default 0,
    constraint ux_mr_item_key unique (analysis_id, item_key)
);
create index ix_mr_item_analysis on mr_item (analysis_id);
