alter table mr_item add column previous_reviewer varchar(120);
alter table mr_item add column changed_parts text;
alter table mr_item add column jira_key varchar(40);

-- Findings nobody needs to review (generated code, docs, CI files): matched files are left out of an analysis.
-- scope = a repo1 path or URL (that project only); null = every project. category null = the whole file.
create table mr_ignore_rule (
    id         bigint generated by default as identity primary key,
    pattern    varchar(500)             not null,
    category   varchar(32),
    scope      varchar(1000),
    note       varchar(1000),
    created_at timestamp with time zone not null
);
